def _cb_fit_predict(X, y, tr_ids, te_ids, params):
    """Fit CatBoost on tr_ids (with an early-stopping sub-split), predict te_ids."""
    cat_idx = [X.columns.get_loc(c) for c in CATEGORICAL_FEATURES if c in X.columns]
    X_cb = _prep_catboost_df(X)
    es_tr, es_va = _early_stop_split(tr_ids, seed=SEED)
    model = CatBoostRegressor(**params)
    model.fit(
        Pool(X_cb.loc[es_tr], y.loc[es_tr].values, cat_features=cat_idx),
        eval_set=Pool(X_cb.loc[es_va], y.loc[es_va].values, cat_features=cat_idx),
    )
    return model.predict(X_cb.loc[te_ids]), model


def _catboost_cv_rmse(params, X, y, folds, trial=None):
    rmses = []
    for step, (tr_ids, te_ids) in enumerate(folds):
        tr = X.index.intersection(tr_ids)
        te = X.index.intersection(te_ids)
        preds, _ = _cb_fit_predict(X, y, list(tr), list(te), params)
        rmses.append(float(np.sqrt(np.mean((preds - y.loc[te].values) ** 2))))
        _maybe_prune(trial, rmses, step)
    return float(np.mean(rmses))


def catboost_objective(trial, X, y, folds):
    params = {
        **CATBOOST_FIXED,
        "iterations": 2000,
        "learning_rate": trial.suggest_float("learning_rate", 1e-3, 0.3, log=True),
        "depth": trial.suggest_int("depth", 3, 10),
        "l2_leaf_reg": trial.suggest_float("l2_leaf_reg", 1e-2, 10, log=True),
        "random_strength": trial.suggest_float("random_strength", 1e-2, 10, log=True),
        "bagging_temperature": trial.suggest_float("bagging_temperature", 0.0, 1.0),
        "border_count": trial.suggest_int("border_count", 32, 255),
    }
    return _catboost_cv_rmse(params, X, y, folds, trial)


