# ElasticNet (with the shared preprocessor)
# ============================================================
def _make_elasticnet_pipe(feature_columns, params):
    return Pipeline([
        ("pre", build_preprocessor(feature_columns)),
        ("en", ElasticNet(**{**ELASTICNET_FIXED, **params})),
    ])


def _elasticnet_cv_rmse(params, X, y, folds, trial=None):
    rmses = []
    for step, (tr_ids, te_ids) in enumerate(folds):
        tr = X.index.intersection(tr_ids)
        te = X.index.intersection(te_ids)
        pipe = _make_elasticnet_pipe(X.columns.tolist(), params)
        pipe.fit(X.loc[tr], y.loc[tr].values)
        preds = pipe.predict(X.loc[te])
        rmses.append(float(np.sqrt(np.mean((preds - y.loc[te].values) ** 2))))
        _maybe_prune(trial, rmses, step)
    return float(np.mean(rmses))


def elasticnet_objective(trial, X, y, folds):
    params = {
        "alpha": trial.suggest_float("alpha", 1e-4, 10.0, log=True),
        "l1_ratio": trial.suggest_float("l1_ratio", 0.0, 1.0),
    }
    return _elasticnet_cv_rmse(params, X, y, folds, trial)


def tune_elasticnet(X, y, folds):
    study = _make_study()
    study.optimize(lambda t: elasticnet_objective(t, X, y, folds),
                   n_trials=_n_trials("elasticnet"), timeout=OPTUNA_TIMEOUT,
                   show_progress_bar=False)
    return dict(study.best_params), study.best_value


