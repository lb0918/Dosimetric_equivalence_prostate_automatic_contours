def load_prep():
    X = pd.read_csv(PREP_DIR / "features.csv", index_col=0)
    y = pd.read_csv(PREP_DIR / "targets.csv", index_col=0)
    # Target provenance (real / model / NaN). It may be missing if the targets
    # were generated by an older version of 01_prepare_target.py, in which case
    # every target is evaluated.
    src_path = PREP_DIR / "targets_source.csv"
    y_source = pd.read_csv(src_path, index_col=0) if src_path.exists() else None
    if y_source is None:
        print("  ! targets_source.csv missing -> evaluating on ALL targets "
              "(real + model). Rerun 01_prepare_target.py for the real-only diagnostic.")
    return X, y, y_source


def get_endpoint_data(X, y_col):
    """Restrict to the patients with a non-NaN y at this endpoint."""
    y = y_col.dropna()
    common = X.index.intersection(y.index)
    return X.loc[common].copy(), y.loc[common].copy()


def real_eval_index(X, y_source, endpoint):
    """Index of the patients whose target at this endpoint is a REAL measurement
    (Case 1), the only ones on which OOF performance is evaluated. If the
    provenance is unknown, fall back to every patient of X."""
    if y_source is None or endpoint not in y_source.columns:
        return X.index
    real_ids = y_source.index[y_source[endpoint] == "real"]
    return X.index[X.index.isin(real_ids)]


def _as_repeat_frame(oof):
    """Normalise an OOF object to a DataFrame (index=record_id, columns=repeats).

    A Series (single partition) is accepted for backward compatibility and
    becomes column 0, so n_repeats=1 behaves exactly as a single partition."""
    if isinstance(oof, pd.Series):
        return oof.to_frame(0)
    return oof


def report_oof(tag, y, oof, eval_idx):
    """Print the OOF metric evaluated ONLY on `eval_idx` (real targets) and,
    as a leakage diagnostic, the metric over ALL targets (real + model).
    Returns the real-only metrics dict.

    Under repeated CV the metrics are POOLED across repetitions, each patient
    contributing r predictions. At r=1 this is identical to a single partition.
    The between-repetition dispersion is printed as well, giving a direct read
    of the instability due to the partition."""
    oof = _as_repeat_frame(oof)
    reps = list(oof.columns)

    yr = y.loc[eval_idx]
    y_pool = pd.concat([yr] * len(reps), ignore_index=True)
    p_pool = pd.concat([oof.loc[eval_idx, r] for r in reps], ignore_index=True)
    mr = y_pool.notna() & p_pool.notna()
    if int(mr.sum()) == 0:
        print(f"        {tag}: no real target to evaluate (n_real=0).")
        return None
    m_real = regression_metrics(y_pool[mr], p_pool[mr])

    y_all = pd.concat([y] * len(reps), ignore_index=True)
    p_all = pd.concat([oof[r] for r in reps], ignore_index=True)
    ma = y_all.notna() & p_all.notna()
    m_all = regression_metrics(y_all[ma], p_all[ma])

    n_real = int(mr.sum()) // len(reps)
    print(f"        OOF real-only (n={n_real}) -> "
          f"RMSE={m_real['rmse']:.3f}  MAE={m_real['mae']:.3f}  R2={m_real['r2']:.3f}"
          f"   | all incl. model (n={int(ma.sum()) // len(reps)}): R2={m_all['r2']:.3f}")
    if len(reps) > 1:
        rmses = []
        for r in reps:
            pr = oof.loc[eval_idx, r]
            m = yr.notna() & pr.notna()
            rmses.append(regression_metrics(yr[m], pr[m])["rmse"])
        print(f"        -> {len(reps)} repetitions: RMSE "
              f"{np.mean(rmses):.3f} +/- {np.std(rmses, ddof=1):.3f} "
              f"[{np.min(rmses):.3f}, {np.max(rmses):.3f}]")
    return m_real


# ============================================================
# Preprocessor shared by MLP / LinReg
# ============================================================
def build_preprocessor(feature_columns):
    cat_cols = [c for c in CATEGORICAL_FEATURES if c in feature_columns]
    num_cols = [c for c in feature_columns if c not in cat_cols]
    num_pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
    ])
    cat_pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
    ])
    return ColumnTransformer([("num", num_pipe, num_cols), ("cat", cat_pipe, cat_cols)])


def _prep_catboost_df(df):
    """CatBoost: impute the categorical columns with the 'missing' string."""
    out = df.copy()
    for c in CATEGORICAL_FEATURES:
        if c in out.columns:
            out[c] = out[c].fillna("missing").astype(str)
    return out


def _early_stop_split(ids, seed):
    """90/10 split of a set of IDs, for internal early stopping."""
    rng = np.random.default_rng(seed)
    arr = np.array(ids)
    rng.shuffle(arr)
    cut = int(0.9 * len(arr))
    return arr[:cut], arr[cut:]


# ============================================================
# Generic NESTED CV engine
# ============================================================
# Every tunable algorithm exposes three callables:
#   tune_fn(X, y, inner_folds)       -> (params_dict, inner_cv_rmse)
#       runs Optuna minimising the inner CV RMSE (inner_folds); returns params
#       directly usable by fitpred_fn / final_fn.
#   fitpred_fn(X, y, tr, te, params) -> preds (np.array aligned on te)
#       trains on the IDs `tr` and predicts the IDs `te`.
#   final_fn(X, y, params, out_dir)  -> None
#       deployable refit on all patients, then serialises the model.
def run_nested_cv(name, tune_fn, fitpred_fn, final_fn, X, y, outer_folds, out_dir):
    """Produce the OOF predictions by nested CV, then train the deployable model.

    `outer_folds` is a list of (repeat, fold, train_ids, test_ids) as produced by
    utils.repeated_kfold_patients. Each repetition is an independent patient-level
    K-fold partition; the deployable model does not depend on any outer partition
    and is therefore tuned and trained ONCE.

    The Optuna tuning of each outer fold uses ONLY the training part of that fold
    (inner CV): the outer test fold never takes part in hyperparameter selection.
    The inner CV seed is SEED+101+k+1000*r, which at r=0 reduces to SEED+101+k.

    Returns a DataFrame (index=record_id, columns=repeats).
    """
    reps = sorted({r for r, _, _, _ in outer_folds})
    oof = pd.DataFrame(np.nan, index=X.index, columns=reps, dtype=float)
    per_fold = []
    for r, k, tr_ids, te_ids in outer_folds:
        tr = list(X.index.intersection(tr_ids))
        te = list(X.index.intersection(te_ids))
        # Inner CV built only on the training part of the outer fold.
        inner_folds = kfold_patients(tr, seed=SEED + 101 + k + 1000 * r,
                                     n_folds=N_INNER_FOLDS)
        params, inner_rmse = tune_fn(X, y, inner_folds)
        preds = fitpred_fn(X, y, tr, te, params)
        oof.loc[te, r] = preds
        per_fold.append({"repeat": r, "fold": k, "params": params,
                         "inner_cv_rmse": inner_rmse})

    # Deployable model: tuning on an inner CV covering all patients, then a
    # refit on all patients. These parameters are NOT used for the OOF above.
    inner_full = kfold_patients(list(X.index), seed=SEED, n_folds=N_INNER_FOLDS)
    deploy_params, deploy_rmse = tune_fn(X, y, inner_full)
    final_fn(X, y, deploy_params, out_dir)

    with open(out_dir / f"best_params_{name}.json", "w") as f:
        json.dump({
            "deployable_params": deploy_params,
            "deployable_inner_cv_rmse": deploy_rmse,
            "per_outer_fold": per_fold,
            "n_outer_folds": len(outer_folds),
            "n_repeats": len(reps),
            "n_inner_folds": N_INNER_FOLDS,
            "n_trials": _n_trials(name),
        }, f, indent=2, default=str)
    return oof


def _n_trials(name):
    """Optuna trial budget for algorithm `name` (fallback: OPTUNA_N_TRIALS)."""
    return OPTUNA_N_TRIALS_BY_ALGO.get(name, OPTUNA_N_TRIALS)


def _make_study():
    return optuna.create_study(
        direction="minimize",
        sampler=optuna.samplers.TPESampler(seed=SEED),
        pruner=optuna.pruners.MedianPruner(
            n_startup_trials=OPTUNA_PRUNER_STARTUP_TRIALS,
            n_warmup_steps=OPTUNA_PRUNER_WARMUP_STEPS,
        ),
    )


def _maybe_prune(trial, rmses, step):
    """Report the running CV RMSE (mean over the folds already evaluated) to
    Optuna at fold `step`, and raise TrialPruned if the study's pruner judges the
    trial unpromising. No-op when no trial is supplied (CV outside tuning)."""
    if trial is None:
        return
    trial.report(float(np.mean(rmses)), step)
    if trial.should_prune():
        raise optuna.TrialPruned()


# ============================================================
# Linear Regression (no hyperparameter, so a plain outer CV = nested CV)
# ============================================================
def cv_linreg(X, y, folds):
    """Repeated K-fold CV producing the OOF predictions.

    `folds` is a list of (repeat, fold, train_ids, test_ids). Returns a
    DataFrame (index=record_id, columns=repeats)."""
    reps = sorted({r for r, _, _, _ in folds})
    oof = pd.DataFrame(np.nan, index=X.index, columns=reps, dtype=float)
    for r, _k, tr_ids, te_ids in folds:
        tr = X.index.intersection(tr_ids)
        te = X.index.intersection(te_ids)
        pipe = Pipeline([("pre", build_preprocessor(X.columns.tolist())),
                         ("lr", LinearRegression())])
        pipe.fit(X.loc[tr], y.loc[tr].values)
        oof.loc[te, r] = pipe.predict(X.loc[te])
    return oof


def fit_final_linreg(X, y, out_dir):
    pipe = Pipeline([("pre", build_preprocessor(X.columns.tolist())),
                     ("lr", LinearRegression())])
    pipe.fit(X, y.values)
    joblib.dump(pipe, out_dir / "linreg.joblib")


