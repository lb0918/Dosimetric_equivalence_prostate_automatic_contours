def final_catboost(X, y, params, out_dir):
    es_tr, es_va = _early_stop_split(list(X.index), seed=SEED + 1)
    cat_idx = [X.columns.get_loc(c) for c in CATEGORICAL_FEATURES if c in X.columns]
    X_cb = _prep_catboost_df(X)
    final = CatBoostRegressor(**params)
    final.fit(
        Pool(X_cb.loc[es_tr], y.loc[es_tr].values, cat_features=cat_idx),
        eval_set=Pool(X_cb.loc[es_va], y.loc[es_va].values, cat_features=cat_idx),
    )
    final.save_model(str(out_dir / "catboost.cbm"))


