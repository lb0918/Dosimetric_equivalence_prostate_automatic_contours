# ============================================================
# XGBoost (shared preprocessor, to handle the one-hot encoding).
# Early stopping through a 90/10 sub-split of the training fold.
# ============================================================
def _xgb_fit_predict(X, y, tr_ids, te_ids, params):
    """Fit XGBoost on tr_ids (with an early-stopping sub-split), predict te_ids.

    The preprocessor is fitted on the early-stopping sub-training set, to avoid
    any leakage through the imputation and scaling statistics.
    """
    es_tr, es_va = _early_stop_split(tr_ids, seed=SEED)
    pre = build_preprocessor(X.columns.tolist())
    pre.fit(X.loc[es_tr])
    X_tr = pre.transform(X.loc[es_tr])
    X_va = pre.transform(X.loc[es_va])
    X_te = pre.transform(X.loc[te_ids])
    y_tr = y.loc[es_tr].values
    y_va = y.loc[es_va].values

    model = xgb.XGBRegressor(**params)
    model.fit(X_tr, y_tr, eval_set=[(X_va, y_va)], verbose=False)
    return model.predict(X_te), model, pre


def _xgboost_cv_rmse(params, X, y, folds, trial=None):
    rmses = []
    for step, (tr_ids, te_ids) in enumerate(folds):
        tr = X.index.intersection(tr_ids)
        te = X.index.intersection(te_ids)
        preds, _, _ = _xgb_fit_predict(X, y, list(tr), list(te), params)
        rmses.append(float(np.sqrt(np.mean((preds - y.loc[te].values) ** 2))))
        _maybe_prune(trial, rmses, step)
    return float(np.mean(rmses))


def xgboost_objective(trial, X, y, folds):
    params = {
        **XGBOOST_FIXED,
        "n_estimators": 2000,
        "learning_rate": trial.suggest_float("learning_rate", 1e-3, 0.3, log=True),
        "max_depth": trial.suggest_int("max_depth", 3, 10),
        "min_child_weight": trial.suggest_float("min_child_weight", 1e-2, 10, log=True),
        "subsample": trial.suggest_float("subsample", 0.5, 1.0),
        "colsample_bytree": trial.suggest_float("colsample_bytree", 0.5, 1.0),
        "reg_alpha": trial.suggest_float("reg_alpha", 1e-3, 10, log=True),
        "reg_lambda": trial.suggest_float("reg_lambda", 1e-3, 10, log=True),
        "gamma": trial.suggest_float("gamma", 1e-3, 5.0, log=True),
    }
    return _xgboost_cv_rmse(params, X, y, folds, trial)


def tune_xgboost(X, y, folds):
    study = _make_study()
    study.optimize(lambda t: xgboost_objective(t, X, y, folds),
                   n_trials=_n_trials("xgboost"), timeout=OPTUNA_TIMEOUT,
                   show_progress_bar=False)
    final_params = {**XGBOOST_FIXED, "n_estimators": 2000, **study.best_params}
    return final_params, study.best_value


def fitpred_xgboost(X, y, tr, te, params):
    preds, _, _ = _xgb_fit_predict(X, y, list(tr), list(te), params)
    return preds


def final_xgboost(X, y, params, out_dir):
    # Preprocessor fitted on the es_tr part of the global split, consistent with
    # the booster.
    es_tr, es_va = _early_stop_split(list(X.index), seed=SEED + 1)
    pre = build_preprocessor(X.columns.tolist())
    pre.fit(X.loc[es_tr])
    X_tr = pre.transform(X.loc[es_tr])
    X_va = pre.transform(X.loc[es_va])
    final = xgb.XGBRegressor(**params)
    final.fit(X_tr, y.loc[es_tr].values, eval_set=[(X_va, y.loc[es_va].values)], verbose=False)
    final.save_model(str(out_dir / "xgboost.json"))
    # XGBoost-specific preprocessor, fitted on es_tr only, hence different from
    # the final MLP/LinReg one.
    joblib.dump(pre, out_dir / "preprocessor_xgboost.joblib")


