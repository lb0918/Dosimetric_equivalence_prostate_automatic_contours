"""
02_train.py
===========
Trains 6 algorithms at every endpoint by patient-level nested cross-validation.

Algorithms: LinReg (baseline), ElasticNet, Random Forest, XGBoost, CatBoost, MLP.

Strategy (NESTED CV - no hyperparameter leakage):
  The OUTER CV (N_FOLDS patient-level folds) produces the out-of-fold
  predictions, one per patient. For each outer fold:
    1) Optuna optimises the hyperparameters through an INNER CV
       (N_INNER_FOLDS folds) built ONLY on the training part of that outer fold.
       The outer test fold is never seen during tuning.
    2) The model is trained with those best parameters on the whole outer
       training set and predicts the outer test fold, giving unbiased OOF
       predictions.
  Hyperparameters may therefore differ from one outer fold to the next.
  (LinReg has no hyperparameter, so a plain outer CV is equivalent to nesting.)

  DEPLOYABLE MODEL: after the nested CV, one more Optuna tuning is run (inner CV
  over all patients), then the model is refitted on all patients with those best
  parameters. Those deployable hyperparameters serve the delivered model only,
  never the OOF predictions.

Outputs in MODELS_DIR/<endpoint>/:
  - linreg.joblib, elasticnet.joblib, rf.joblib,
    xgboost.json, catboost.cbm, mlp.pt      (final deployable models)
  - preprocessor.joblib                     (fitted on all patients)
  - best_params_<algo>.json                 (deployable params, per-outer-fold
                                             params, and inner CV RMSE)
  - oof_predictions.csv                     (record_id, repeat, fold, source,
                                             y_true, and one column per algorithm)

LEAKAGE DIAGNOSTIC: the OOF metrics printed here are computed only on the "real"
targets (a real measurement inside the window, see targets_source.csv). The
"model" targets, imputed by the trajectory model of 01_prepare_target.py, are
used for TRAINING (training folds) but never evaluated, otherwise performance
would be inflated by smoothed, denoised targets. The `source` column of
oof_predictions.csv allows the metrics to be re-sliced afterwards.
"""
