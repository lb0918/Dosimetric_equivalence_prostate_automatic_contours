def main():
    print("=" * 70)
    print("TRAINING - 6 algorithms x every endpoint - patient-level NESTED CV")
    print(f"  Outer CV: {N_FOLDS} folds (OOF)  |  Inner CV: {N_INNER_FOLDS} folds (tuning)")
    print(f"PyTorch device: {DEVICE}")
    print("=" * 70)
    ensure_dir(MODELS_DIR)

    X_full, y_full, src_full = load_prep()
    print(f"[ok] Loaded: {X_full.shape[0]} patients x {X_full.shape[1]} features")

    for endpoint in y_full.columns:
        print(f"\n{'-' * 70}\n>>> Endpoint: {endpoint}\n{'-' * 70}")
        X, y = get_endpoint_data(X_full, y_full[endpoint])
        n = len(X)
        # EVALUATION index = real targets (Case 1) only. Targets imputed by the
        # trajectory model stay in X/y to TRAIN (training folds), but are never
        # counted in the OOF metrics.
        eval_idx = real_eval_index(X, src_full, endpoint)
        n_real = len(eval_idx)
        print(f"  Usable patients: {n}  ({n_real} real targets evaluated, "
              f"{n - n_real} model-imputed - training only)")
        if n < 30:
            print(f"  ! Too few patients (< 30) - skipping {endpoint}")
            continue
        if n_real == 0:
            print(f"  ! No real target for {endpoint} - OOF metrics not interpretable.")

        out_dir = ensure_dir(MODELS_DIR / endpoint)

        # Preprocessor fitted on all patients, for SHAP and deployment (the MLP
        # step saves an identical one).
        pre_full = build_preprocessor(X.columns.tolist())
        pre_full.fit(X)
        joblib.dump(pre_full, out_dir / "preprocessor.joblib")

        # Patient-level outer folds - the same folds for every algorithm.
        # N_REPEATS independent partitions; at N_REPEATS=1 this is exactly
        # kfold_patients(X.index, seed=SEED, n_folds=N_FOLDS).
        folds = repeated_kfold_patients(X.index, seed=SEED, n_folds=N_FOLDS,
                                        n_repeats=N_REPEATS)
        fold_assignment = {(r, pid): f for r, f, _, te in folds for pid in te}

        # ----- LinReg (no tuning) -----
        print(f"  [1/6] Linear Regression (baseline) - {N_FOLDS}-fold CV"
              f"{f' x{N_REPEATS} repetitions' if N_REPEATS > 1 else ''}...")
        oof_lr = cv_linreg(X, y, folds)
        fit_final_linreg(X, y, out_dir)
        report_oof("LinReg", y, oof_lr, eval_idx)

        # ----- ElasticNet -----
        print(f"  [2/6] ElasticNet - nested CV (Optuna {_n_trials('elasticnet')} trials)...")
        oof_en = run_nested_cv("elasticnet", tune_elasticnet, fitpred_elasticnet,
                               final_elasticnet, X, y, folds, out_dir)
        report_oof("ElasticNet", y, oof_en, eval_idx)

        # ----- Random Forest -----
        print(f"  [3/6] Random Forest - nested CV (Optuna {_n_trials('rf')} trials)...")
        oof_rf = run_nested_cv("rf", tune_rf, fitpred_rf,
                               final_rf, X, y, folds, out_dir)
        report_oof("RandomForest", y, oof_rf, eval_idx)

        # ----- XGBoost -----
        print(f"  [4/6] XGBoost - nested CV (Optuna {_n_trials('xgboost')} trials)...")
        oof_xgb = run_nested_cv("xgboost", tune_xgboost, fitpred_xgboost,
                                final_xgboost, X, y, folds, out_dir)
        report_oof("XGBoost", y, oof_xgb, eval_idx)

        # ----- CatBoost -----
        print(f"  [5/6] CatBoost - nested CV (Optuna {_n_trials('catboost')} trials)...")
        oof_cb = run_nested_cv("catboost", tune_catboost, fitpred_catboost,
                               final_catboost, X, y, folds, out_dir)
        report_oof("CatBoost", y, oof_cb, eval_idx)

        # ----- MLP -----
        print(f"  [6/6] MLP - nested CV (Optuna {_n_trials('mlp')} trials)...")
        oof_mlp = run_nested_cv("mlp", tune_mlp, fitpred_mlp,
                                final_mlp, X, y, folds, out_dir)
        report_oof("MLP", y, oof_mlp, eval_idx)

        # Dump the OOF predictions in LONG format, one row per (patient,
        # repetition). At N_REPEATS=1 there is a single row per patient and the
        # `repeat` column is 0 everywhere, so the file is a strict superset of
        # the single-partition format and readers ignoring `repeat` stay
        # correct. Beyond that, EVERY consumer must join on (record_id, repeat):
        # a merge on record_id alone would silently produce a cartesian product.
        src_col = (src_full[endpoint].reindex(X.index)
                   if src_full is not None else pd.Series("unknown", index=X.index))
        preds = {"linreg": oof_lr, "elasticnet": oof_en, "rf": oof_rf,
                 "xgboost": oof_xgb, "catboost": oof_cb, "mlp": oof_mlp}
        preds = {k: _as_repeat_frame(v) for k, v in preds.items()}
        blocks = []
        for r in range(N_REPEATS):
            block = pd.DataFrame({
                "record_id": list(X.index),
                "repeat": r,
                "fold": [fold_assignment[(r, pid)] for pid in X.index],
                "source": src_col.values,      # real (evaluated) / model (training only)
                "y_true": y.values,
            })
            for algo, frame in preds.items():
                block[algo] = frame[r].values
            blocks.append(block)
        pd.concat(blocks, ignore_index=True).to_csv(
            out_dir / "oof_predictions.csv", index=False)

    print(f"\n[done] All models trained. Results in {MODELS_DIR}/")


if __name__ == "__main__":
    main()
