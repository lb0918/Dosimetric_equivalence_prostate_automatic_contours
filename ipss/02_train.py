# MLP
# ============================================================
class MLP(nn.Module):
    def __init__(self, n_in, hidden_sizes, dropout):
        super().__init__()
        layers, prev = [], n_in
        for h in hidden_sizes:
            layers += [nn.Linear(prev, h), nn.ReLU(), nn.Dropout(dropout)]
            prev = h
        layers.append(nn.Linear(prev, 1))
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x).squeeze(-1)


def _to_tensor(arr):
    return torch.tensor(arr, dtype=torch.float32, device=DEVICE)


def _train_mlp(X_tr, y_tr, X_va, y_va, params):
    """MLP training loop with early stopping. Returns (model, best_val_rmse)."""
    torch.manual_seed(SEED)
    model = MLP(X_tr.shape[1], params["hidden_sizes"], params["dropout"]).to(DEVICE)
    opt = torch.optim.Adam(model.parameters(), lr=params["lr"],
                           weight_decay=params["weight_decay"])
    loss_fn = nn.MSELoss()
    X_tr_t, y_tr_t = _to_tensor(X_tr), _to_tensor(y_tr)
    X_va_t = _to_tensor(X_va)
    n = X_tr_t.shape[0]

    best_state, best_val, patience = None, float("inf"), 0
    for _ in range(MLP_MAX_EPOCHS):
        model.train()
        perm = torch.randperm(n, device=DEVICE)
        for i in range(0, n, MLP_BATCH_SIZE):
            idx = perm[i:i + MLP_BATCH_SIZE]
            opt.zero_grad()
            loss = loss_fn(model(X_tr_t[idx]), y_tr_t[idx])
            loss.backward()
            opt.step()
        model.eval()
        with torch.no_grad():
            va_pred = model(X_va_t).cpu().numpy()
        va_rmse = float(np.sqrt(np.mean((va_pred - y_va) ** 2)))
        if va_rmse < best_val - 1e-5:
            best_val = va_rmse
            best_state = {k: v.detach().clone() for k, v in model.state_dict().items()}
            patience = 0
        else:
            patience += 1
            if patience >= MLP_PATIENCE:
                break
    model.load_state_dict(best_state)
    return model, best_val


def _mlp_fit_predict(X, y, tr, te, params):
    """Fit the MLP on the IDs `tr` (internal preprocessor and early stopping),
    then predict `te`.

    The preprocessor is fitted on the early-stopping sub-training set
    (es_tr, a subset of tr), never on `te`.
    """
    es_tr, es_va = _early_stop_split(tr, seed=SEED)
    pre = build_preprocessor(X.columns.tolist())
    pre.fit(X.loc[es_tr])
    X_tr = pre.transform(X.loc[es_tr]).astype(np.float32)
    X_va = pre.transform(X.loc[es_va]).astype(np.float32)
    X_te = pre.transform(X.loc[te]).astype(np.float32)
    y_tr = y.loc[es_tr].values.astype(np.float32)
    y_va = y.loc[es_va].values.astype(np.float32)

    model, _ = _train_mlp(X_tr, y_tr, X_va, y_va, params)
    model.eval()
    with torch.no_grad():
        return model(_to_tensor(X_te)).cpu().numpy()


def _mlp_cv_rmse(X, y, folds, params, trial=None):
    """Mean CV RMSE, with the preprocessor fitted INSIDE each fold."""
    rmses = []
    for step, (tr_ids, te_ids) in enumerate(folds):
        tr = list(X.index.intersection(tr_ids))
        te = list(X.index.intersection(te_ids))
        preds = _mlp_fit_predict(X, y, tr, te, params)
        y_te = y.loc[te].values.astype(np.float32)
        rmses.append(float(np.sqrt(np.mean((preds - y_te) ** 2))))
        _maybe_prune(trial, rmses, step)
    return float(np.mean(rmses))


def _mlp_params_from_trial(best):
    """Rebuild a usable params dict from Optuna's best_params."""
    n_layers = best["n_layers"]
    return {
        "hidden_sizes": [best[f"h{i}"] for i in range(n_layers)],
        "dropout": best["dropout"],
        "lr": best["lr"],
        "weight_decay": best["weight_decay"],
    }


def mlp_objective(trial, X, y, folds):
    n_layers = trial.suggest_int("n_layers", 1, 3)
    hidden = [trial.suggest_categorical(f"h{i}", [16, 32, 64, 128]) for i in range(n_layers)]
    params = {
        "hidden_sizes": hidden,
        "dropout": trial.suggest_float("dropout", 0.0, 0.5),
        "lr": trial.suggest_float("lr", 1e-4, 1e-2, log=True),
        "weight_decay": trial.suggest_float("weight_decay", 1e-6, 1e-2, log=True),
    }
    return _mlp_cv_rmse(X, y, folds, params, trial)


def tune_mlp(X, y, folds):
    study = _make_study()
    study.optimize(lambda t: mlp_objective(t, X, y, folds),
                   n_trials=_n_trials("mlp"), timeout=OPTUNA_TIMEOUT,
                   show_progress_bar=False)
    return _mlp_params_from_trial(study.best_params), study.best_value


def fitpred_mlp(X, y, tr, te, params):
    return _mlp_fit_predict(X, y, tr, te, params)


def final_mlp(X, y, params, out_dir):
    # Preprocessor fitted on everything (deployment); 90/10 sub-split for early
    # stopping.
    pre = build_preprocessor(X.columns.tolist())
    pre.fit(X)
    # NB: overwrites the preprocessor.joblib saved earlier (identical, deterministic).
    joblib.dump(pre, out_dir / "preprocessor.joblib")
    X_all = pre.transform(X).astype(np.float32)
    y_all = y.values.astype(np.float32)
    es_tr, es_va = _early_stop_split(np.arange(len(X_all)), seed=SEED + 2)
    model, _ = _train_mlp(X_all[es_tr], y_all[es_tr], X_all[es_va], y_all[es_va], params)
    torch.save({"state_dict": model.state_dict(),
                "n_in": X_all.shape[1],
                "params": params}, out_dir / "mlp.pt")


